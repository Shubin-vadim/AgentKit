"""Render the generated website pages as Markdown."""

from itertools import groupby

from site_catalog.models import ProfileEntry, SkillEntry
from site_catalog.utils import display_name, table_cell

SKILLS_PAGE = "skills.md"
GENERATED_NOTE = "<!-- Generated by website/build_catalog.py. Do not edit. -->"
ORIGINAL_SOURCE = "Agent kit"
SKILLS_INTRO = """\
Every skill in the public library, grouped by folder. A skill is installed
with each profile listed next to it. Skills marked with a source are vendored
from that project and keep its license; the rest are original to Agent kit.
"""
PROFILES_INTRO = """\
A profile is one install list. `core` is always added; pick the others for the
work planned in a project, for example `--profile architecture,engineering`.
"""
SKILL_TABLE_HEAD = "| Skill | What it does | Profiles | Source |\n|---|---|---|---|"


class PageRenderer:
    """Turns catalog entries into the skills and profiles pages."""

    def skills_page(self, skills: list[SkillEntry]) -> str:
        """Render the skill catalog.

        :param skills: Skills sorted by group, then name.
        :return: Markdown with one section per top folder and a table per group.
        """
        parts = [GENERATED_NOTE, "# Skills", SKILLS_INTRO.strip()]
        for top, top_items in groupby(skills, key=lambda s: s.group[0]):
            parts.append(f"## {display_name(top)}")
            for group, items in groupby(top_items, key=lambda s: s.group):
                if len(group) > 1:
                    parts.append(f"### {display_name(group[-1])}")
                rows = [self._skill_row(skill) for skill in items]
                parts.append("\n".join([SKILL_TABLE_HEAD, *rows]))
        return "\n\n".join(parts) + "\n"

    def profiles_page(self, profiles: list[ProfileEntry]) -> str:
        """Render the profile reference.

        :param profiles: Profiles in display order.
        :return: Markdown with one section per profile.
        """
        parts = [GENERATED_NOTE, "# Profiles", PROFILES_INTRO.strip()]
        for profile in profiles:
            parts.append(f"## {profile.name}")
            if profile.summary:
                parts.append(profile.summary)
            parts.append(self._contents(profile))
        return "\n\n".join(parts) + "\n"

    @staticmethod
    def _skill_row(skill: SkillEntry) -> str:
        anchor = f'<a id="{skill.name}"></a>`{skill.name}`'
        profiles = ", ".join(f"[{p}](profiles.md#{p})" for p in skill.profiles)
        source = (
            f"[{skill.source.label}]({skill.source.url})"
            if skill.source
            else ORIGINAL_SOURCE
        )
        cells = [anchor, table_cell(skill.summary), profiles or "—", source]
        return f"| {' | '.join(cells)} |"

    @staticmethod
    def _contents(profile: ProfileEntry) -> str:
        skills = ", ".join(f"[`{s}`]({SKILLS_PAGE}#{s})" for s in profile.skills)
        lines = [
            ("Skills", skills),
            ("Rules", ", ".join(f"`{r}`" for r in profile.rules)),
            ("MCP servers", ", ".join(f"`{m}`" for m in profile.mcp)),
            ("Templates", ", ".join(f"`{t}`" for t in profile.templates)),
        ]
        return "\n".join(f"- **{label}:** {value}" for label, value in lines if value)

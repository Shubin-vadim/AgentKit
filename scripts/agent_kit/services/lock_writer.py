"""Write ``.agent-kit.lock`` into the target."""

import datetime
from pathlib import Path

from agent_kit.files import TargetWriter
from agent_kit.git_repository import GitRepository
from agent_kit.models import LockContents

LOCK_NAME = ".agent-kit.lock"
HEADER = "# Generated by agent-kit (scripts/kit.py install). Do not edit by hand."
LIST_FIELDS = ("clients", "profiles", "skills", "rules", "mcp", "templates")


class LockWriter:
    """Records what was installed and from which kit and library revisions."""

    def write(self, writer: TargetWriter, contents: LockContents) -> None:
        """Write the lock file (a small YAML document) into the target.

        :param writer: Writer bound to the target.
        :param contents: What to record.
        """
        path = writer.root / LOCK_NAME
        writer.report("lock", path)
        kit = GitRepository(contents.kit_root)
        lines = [
            HEADER,
            f'kit_root: "{contents.kit_root.as_posix()}"',
            f"kit_revision: {kit.revision()}",
            f"kit_dirty: {kit.dirty()}",
            *self._libraries(contents.libraries),
            f"applied_at: {datetime.datetime.now(datetime.UTC):%Y-%m-%dT%H:%M:%SZ}",
        ]
        for field in LIST_FIELDS:
            lines += self._list(field, getattr(contents, field))
        writer.write_text(path, "\n".join(lines) + "\n")

    @staticmethod
    def _libraries(libraries: tuple[Path, ...]) -> list[str]:
        if not libraries:
            return []
        lines = ["libraries:"]
        for library in libraries:
            repo = GitRepository(library)
            lines += [
                f'  - path: "{library.as_posix()}"',
                f"    revision: {repo.revision()}",
                f"    dirty: {repo.dirty()}",
            ]
        return lines

    @staticmethod
    def _list(key: str, values: tuple[str, ...]) -> list[str]:
        if not values:
            return [f"{key}: []"]
        return [f"{key}:", *(f"  - {value}" for value in values)]
